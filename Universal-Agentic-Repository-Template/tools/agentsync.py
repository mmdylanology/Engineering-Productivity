import os, sys

def sync(check=False):
    root_agents = open("AGENTS.md").read()
    claude_target = "<!-- GENERATED by tools/agentsync.py. Do not edit manually. -->\n@AGENTS.md\n"
    if check:
        if open("CLAUDE.md").read() != claude_target:
            print("ERROR: CLAUDE.md is out of sync with AGENTS.md!", file=sys.stderr)
            sys.exit(1)
        print("OK: Agent adapters are in sync.")
    else:
        with open("CLAUDE.md", "w") as f:
            f.write(claude_target)
        print("Generated CLAUDE.md from AGENTS.md")

if __name__ == "__main__":
    is_check = "--check" in sys.argv
    sync(check=is_check)
